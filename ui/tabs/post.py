    def create_removal_button(self, product_widget):
        """
        :purpose: creates a removal button for a specific product line widget
        :param product_widget: the widget to remove when button is clicked
        :return: QPushButton configured to remove the specified widget
        :author(s): Joe Lee
        """
        remove_btn = QPushButton("Remove Product Line")
        remove_btn.setObjectName("red_btn")
        remove_btn.product_widget = product_widget
        remove_btn.clicked.connect(self.on_removal_clicked)
        return remove_btn

    def on_removal_clicked(self):
        """
        :purpose: handles removal of product line
        :return(s): None
        :author(s): Joe Lee
        """
        button = self.sender()
        if hasattr(button, 'product_widget'):
            self.remove_product_line(button.product_widget)

    def remove_product_line(self, product_widget):
        """
        :purpose: removes a specific product line widget
        :param product_widget: the product line widget to remove
        :return: None
        :author(s): Joe Lee
        """
        # Remove from product_sections
        if product_widget in self.product_sections:
            #todo: prevent removal of product line that contains live data
            self.product_sections.remove(product_widget)

        # Remove from layout
        self.products_layout.removeWidget(product_widget)
        product_widget.deleteLater()

        self.product_counter -= 1
        if self.status_label:
            self.status_label.setText(f"Removed product line. Total: {len(self.product_sections)}")

    def add_product_section(self):
        """
        :purpose: adds additional product lines
        :return: None
        :author(s): Joe Lee
        """
        # Product section container
        section_widget = QWidget()
        section_layout = QVBoxLayout(section_widget)
        section_layout.setContentsMargins(0, 0, 0, 0)

        # Line 1: Product ID and Product Name
        line1_layout = QHBoxLayout()

        # Product ID - Fixed width for 10 integers
        line1_layout.addWidget(QLabel("Product ID:"))
        product_id_input = QLineEdit()
        product_id_input.setPlaceholderText("10 INTS")
        product_id_input.setMaxLength(10)
        product_id_input.setFixedWidth(120)
        line1_layout.addWidget(product_id_input)

        # Product Name - Takes up remaining space
        line1_layout.addWidget(QLabel("Product Name:"))
        product_name_input = QLineEdit()
        product_name_input.setPlaceholderText("Product name")
        line1_layout.addWidget(product_name_input)

        # Create removal button for this specific line
        remove_btn = self.create_removal_button(section_widget)
        line1_layout.addWidget(remove_btn)
        section_layout.addLayout(line1_layout)

        # Line 2: Notes, Price, Quantity
        line2_layout = QHBoxLayout()

        # Notes - Takes up most of the space
        line2_layout.addWidget(QLabel("Notes:"))
        notes_input = QLineEdit()
        notes_input.setPlaceholderText("Product notes")
        line2_layout.addWidget(notes_input)

        # Price - Fixed width
        line2_layout.addWidget(QLabel("Price:"))
        price_input = QLineEdit()
        price_input.setPlaceholderText("$0.00")
        price_input.setFixedWidth(100)
        line2_layout.addWidget(price_input)

        # Quantity - Fixed width (same as price)
        line2_layout.addWidget(QLabel("Quantity:"))
        quantity_input = QLineEdit()
        quantity_input.setPlaceholderText("0")
        quantity_input.setFixedWidth(100)
        line2_layout.addWidget(quantity_input)

        section_layout.addLayout(line2_layout)

        # Store the input fields in the widget for later access
        section_widget.product_id_input = product_id_input
        section_widget.product_name_input = product_name_input
        section_widget.notes_input = notes_input
        section_widget.price_input = price_input
        section_widget.quantity_input = quantity_input

        # Add to container
        self.products_layout.addWidget(section_widget)
        self.product_sections.append(section_widget)
        self.product_counter += 1

        # Update status only if status_label exists
        if self.status_label:
            self.status_label.setText(f"Added product line. Total: {len(self.product_sections)}")

